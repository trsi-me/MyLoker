function getLang() {
    return localStorage.getItem('mylocker_lang') || 'ar';
}

function setLang(code) {
    if (code !== 'ar' && code !== 'en') {
        code = 'ar';
    }
    localStorage.setItem('mylocker_lang', code);
    applyLang();
}

function t(key) {
    const code = getLang();
    return (LANG[code] && LANG[code][key]) || LANG.en[key] || key;
}

window.t = t;
window.getLang = getLang;
window.setLang = setLang;
window.applyLang = applyLang;

function applyLang() {
    const code = getLang();
    document.documentElement.lang = code === 'ar' ? 'ar' : 'en';
    document.documentElement.dir = code === 'ar' ? 'rtl' : 'ltr';

    document.querySelectorAll('[data-i18n]').forEach((el) => {
        const k = el.getAttribute('data-i18n');
        if (k && t(k)) {
            el.textContent = t(k);
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((el) => {
        const k = el.getAttribute('data-i18n-placeholder');
        if (k && t(k)) {
            el.setAttribute('placeholder', t(k));
        }
    });

    const ptk = document.body.getAttribute('data-page-title-key');
    if (ptk && t(ptk)) {
        document.title = t(ptk) + ' — MyLocker';
    }

    const pwdInput = document.getElementById('password');
    const pwdToggle = document.getElementById('togglePassword');
    if (pwdInput && pwdToggle && typeof t === 'function') {
        pwdToggle.textContent = pwdInput.type === 'password' ? t('password_show') : t('password_hide');
    }

    document.dispatchEvent(new CustomEvent('mylocker:langchange', { detail: { lang: code } }));
}

document.addEventListener('DOMContentLoaded', () => {
    applyLang();
    function flip() {
        setLang(getLang() === 'ar' ? 'en' : 'ar');
    }
    document.querySelectorAll('#langToggle, #footerLangToggle, .js-lang-toggle').forEach((btn) => {
        btn.addEventListener('click', flip);
    });
});
